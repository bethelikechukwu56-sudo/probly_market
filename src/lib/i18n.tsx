function isLocale(value: string | null): value is LocaleId {
  return LOCALES.some((item) => item.id === value);
}

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] === undefined ? `{${key}}` : String(vars[key]),
  );
}

function applyLocale(locale: LocaleId) {
  const meta = LOCALES.find((item) => item.id === locale) ?? LOCALES[0];
  document.documentElement.lang = locale;
  document.documentElement.dir = meta.dir;
}

type I18nContextValue = {
  locale: LocaleId;
  dir: "ltr" | "rtl";
  setLocale: (locale: LocaleId) => void;
  t: (key: MsgKey | `category.${string}`, vars?: Record<string, string | number>) => string;
  dateLocale: DateLocale;
  intlTag: string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<LocaleId>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    const next: LocaleId = isLocale(stored) ? stored : "en";
    setLocaleState(next);
    applyLocale(next);
  }, []);

  const setLocale = useCallback((next: LocaleId) => {
    setLocaleState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* ignore */
    }
    applyLocale(next);
  }, []);

  const t = useCallback(
    (key: MsgKey | `category.${string}`, vars?: Record<string, string | number>) =>
      interpolate(
        EXTRA[locale]?.[key] ?? (DICTS[locale] as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key,
        vars,
      ),
    [locale],
  );

  const meta = LOCALES.find((item) => item.id === locale) ?? LOCALES[0];
  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      dir: meta.dir,
      setLocale,
      t,
      dateLocale: DATE_LOCALES[locale],
      intlTag: INTL_TAGS[locale],
    }),
    [locale, meta.dir, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

